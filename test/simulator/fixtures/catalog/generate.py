#!/usr/bin/env python3
"""Build the invented cover art used by the approved Library mockup fixture."""
from pathlib import Path
from PIL import Image, ImageDraw, ImageFont
root = Path(__file__).resolve().parent
font = ImageFont.truetype('/System/Library/Fonts/Supplemental/Georgia Bold.ttf', 16)
titles = ['Glasswater', 'Paper\nCoast', 'Quiet\nHarbour', 'Moon\nAtlas']
rows = []
for n, title in enumerate(titles):
    image = Image.new('1', (98, 110), 0 if n == 2 else 1)
    bayer = ((0,8,2,10),(12,4,14,6),(3,11,1,9),(15,7,13,5))
    for y in range(110):
        for x in range(98):
            if n == 2 and bayer[y%4][x%4] < 3: image.putpixel((x,y), 1)
            elif n in (0,3) and bayer[y%4][x%4] == 0: image.putpixel((x,y), 0)
    draw = ImageDraw.Draw(image)
    if n == 1:
        for offset in range(-110, 120, 18):
            for y in range(110):
                x = offset + 110 - y
                if 0 <= x < 98 and y % 4 == 0: draw.point((x,y), fill=0)
    draw.rectangle((0, 0, 97, 109), outline=0)
    if n == 3:
        draw.rectangle((3, 3, 94, 106), outline=0)
    bounds = draw.multiline_textbbox((0, 0), title, font=font, align='center', spacing=2)
    # Draw on an opaque label so hatching remains legible, as in the mockup.
    width, height = bounds[2] - bounds[0], bounds[3] - bounds[1]
    draw.multiline_text(((98-width)//2, (110-height)//2-bounds[1]), title, font=font, fill=1 if n==2 else 0, align='center', spacing=2)
    data = bytearray()
    for y in range(110):
        for x in range(0, 98, 8):
            value = 0
            for bit in range(8):
                if x+bit >= 98 or image.getpixel((x+bit, y)): value |= 0x80 >> bit
            data.append(value)
    rows.append(data)
text = '// Synthetic approved-gallery cover fixture; generated by generate.py.\n#pragma once\n#include <cstdint>\ninline constexpr uint8_t catalogArtwork[4][1430] = {\n'
for data in rows:
    text += '{\n' + '\n'.join(','.join(str(x) for x in data[i:i+32])+',' for i in range(0,len(data),32)) + '\n},\n'
(root/'Artwork.h').write_text(text+'};\n')
